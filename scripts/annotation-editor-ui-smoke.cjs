const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { _electron: electron } = require('playwright')
const { PDFDocument, PDFName, PDFHexString } = require('pdf-lib')
const root = path.resolve(__dirname, '..')
const version = require('../package.json').version
const content = Array.from({ length: 80 }, (_, i) => `Long annotation ${i + 1}: 中文 Arabic العربية and editable text.`).join('\n')

async function select(editor, start, end) {
  await editor.evaluate((element, [start, end]) => {
    element.focus()
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
    const nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode)
    const locate = offset => { for (const node of nodes) { if (offset <= node.textContent.length) return [node, offset]; offset -= node.textContent.length } return [element, 0] }
    const range = document.createRange(); range.setStart(...locate(start)); range.setEnd(...locate(end))
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
  }, [start, end])
}

async function main() {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'pdfuck-rich-editor-'))
  const file = path.join(temporary, 'rich-annotation.pdf')
  const document = await PDFDocument.create(), pdfPage = document.addPage([612, 792])
  pdfPage.node.addAnnot(document.context.register(document.context.obj({ Type: 'Annot', Subtype: 'Text', Rect: [40, 700, 60, 720], Contents: PDFHexString.fromText(content), NM: PDFHexString.fromText('rich-test'), T: PDFHexString.fromText('Reviewer') })))
  await fs.writeFile(file, await document.save())
  const output = path.join(root, 'output', 'playwright'); await fs.mkdir(output, { recursive: true })
  let app
  const launch = async () => {
    app = await electron.launch({ executablePath: process.env.PDFUCK_SMOKE_EXECUTABLE || require('electron'), args: process.env.PDFUCK_SMOKE_EXECUTABLE ? [`--user-data-dir=${temporary}`, file] : [path.join(root, 'out/main/index.js'), file], env: { ...process.env, PDFUCK_TEST_USER_DATA: temporary, PDFUCK_TEST_UPDATE_VERSION: version } })
    const page = await app.firstWindow()
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 700))
    await page.locator('.pdf-page').first().waitFor()
    await page.locator('.nav-rail button').filter({ hasText: '批注' }).click()
    return page
  }
  const close = async () => { await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())); await app.close(); app = undefined }
  try {
    let page = await launch()
    const row = page.locator('.annotation-row').first()
    assert.equal(await row.locator('.annotation-settings-button, textarea').count(), 0)
    await row.locator('.annotation-content-value').dblclick()
    const dialog = page.locator('.annotation-dialog')
    const editor = dialog.locator('.rich-editor-content').first()
    assert.equal(await editor.innerText(), content)
    // Check actual glyph rendering, not only the stored italic flag.
    await editor.fill('123 ABC 中文')
    const snapshot = async () => {
      await editor.evaluate(element => { window.getSelection().removeAllRanges(); element.blur() })
      return editor.screenshot({ caret: 'hide', animations: 'disabled' })
    }
    const normal = await snapshot()
    await select(editor, 0, 10)
    await dialog.locator('.rich-editor-toolbar').first().getByRole('button', { name: '斜体', exact: true }).click()
    const italic = await snapshot()
    const italicRendering = await editor.evaluate(element => ({ synthesis: getComputedStyle(element).fontSynthesis, html: element.innerHTML }))
    console.log(JSON.stringify({ italicRendering, changedPixels: !normal.equals(italic) }))
    assert.ok(!normal.equals(italic), 'Italic must visibly change the rendered letters, numbers and Chinese glyphs')
    await select(editor, 0, 10)
    await page.keyboard.press('Control+i')
    assert.ok(normal.equals(await snapshot()), 'Italic shortcut must restore the original rendering')
    assert.equal(await dialog.locator('.annotation-dialog-heading > span, .window-scroll-body > p').count(), 0)
    assert.equal(await dialog.locator('.annotation-reply-section').getAttribute('open'), null)
    assert.equal(await dialog.locator('.annotation-reply-picker .rich-editor-content').isVisible(), false)
    const toolbar = dialog.locator('.rich-editor-toolbar').first()
    const formatBox = await toolbar.getByRole('button', { name: '斜体', exact: true }).boundingBox()
    const colorButton = toolbar.locator('.annotation-swatches button').nth(3)
    const colorBox = await colorButton.boundingBox()
    assert.ok(Math.abs(formatBox.y - colorBox.y) < 2 && Math.abs(formatBox.height - colorBox.height) < 2, 'Color and format controls must share one row and size')
    await page.screenshot({ path: path.join(output, `annotation-compact-editor-${version}.png`) })
    await dialog.locator('.annotation-dialog-close').click()
    await row.locator('.annotation-content-value').dblclick()
    await dialog.locator('.rich-editor-toolbar .annotation-swatches button').nth(3).click()
    const bounds = await dialog.evaluate(element => {
      const header = element.querySelector('.annotation-dialog-heading'), body = element.querySelector('.window-scroll-body'), editor = element.querySelector('.rich-editor-content')
      const before = header.getBoundingClientRect().top
      body.scrollTop = body.scrollHeight
      return { before, after: header.getBoundingClientRect().top, headerBottom: header.getBoundingClientRect().bottom, bodyTop: body.getBoundingClientRect().top, editorHeight: editor.clientHeight, editorScroll: editor.scrollHeight, scrollTop: body.scrollTop, parentOverflow: getComputedStyle(element).overflowY }
    })
    assert.equal(bounds.before, bounds.after)
    assert.ok(bounds.bodyTop >= bounds.headerBottom - 1)
    assert.equal(bounds.parentOverflow, 'hidden')
    assert.equal(bounds.editorHeight, bounds.editorScroll, 'Long text must expand within the window body')
    await page.screenshot({ path: path.join(output, `annotation-long-body-${version}.png`) })
    assert.ok(bounds.scrollTop > 0, JSON.stringify(bounds))
    await editor.scrollIntoViewIfNeeded()
    await select(editor, 0, 4)
    await page.keyboard.press('Control+b'); await page.keyboard.press('Control+i'); await page.keyboard.press('Control+u'); await page.keyboard.press('Control+Shift+h')
    const reply = dialog.locator('.annotation-reply-picker .rich-editor-content')
    await dialog.locator('.annotation-reply-section > summary').click()
    await reply.fill('Reply 中文\nSecond line')
    await select(reply, 0, 5)
    await dialog.locator('.annotation-reply-picker').getByRole('button', { name: '粗体', exact: true }).click()
    await dialog.locator('.annotation-reply-picker').getByRole('button', { name: '斜体', exact: true }).click()
    assert.equal(await reply.evaluate(element => getComputedStyle(element).fontSynthesisStyle), 'auto')
    await page.screenshot({ path: path.join(output, `annotation-rich-editor-${version}.png`) })
    await dialog.locator('.annotation-reply-section > summary').click()
    assert.equal(await reply.isVisible(), false)
    await dialog.locator('.modal-actions .primary').click()
    await page.locator('.quick-save').click()
    await page.waitForFunction(() => document.querySelector('.quick-save')?.disabled)
    await close()
    const saved = await PDFDocument.load(await fs.readFile(file))
    const dictionary = saved.context.lookup(saved.getPage(0).node.Annots().get(0))
    const savedReplyMarks = JSON.parse(dictionary.get(PDFName.of('PDFuckReplyMarks')).decodeText())
    assert.ok(savedReplyMarks.some(mark => mark.start === 0 && mark.end >= 5 && mark.bold && mark.italic), 'Reply bold and italic must survive saving while collapsed')
    const marks = JSON.parse(dictionary.get(PDFName.of('PDFuckMarks')).decodeText())
    assert.ok(marks.some(mark => mark.start === 0 && mark.end >= 4 && mark.bold && mark.italic && mark.underline && mark.highlight), JSON.stringify(marks.slice(0, 5)))
    assert.deepEqual(dictionary.get(PDFName.of('C')).asArray().map(value => Math.round(value.asNumber() * 255)), [226, 75, 79], 'Toolbar color must be saved')
    assert.ok(dictionary.get(PDFName.of('RC')).decodeText().includes('font-weight:bold'))
    page = await launch()
    await page.locator('.annotation-content-value').first().dblclick()
    assert.equal(await page.locator('.annotation-dialog .rich-editor-content').first().innerText(), content)
    assert.equal(await page.locator('.annotation-reply-section').getAttribute('open'), null)
    await page.locator('.annotation-reply-section > summary').click()
    assert.equal(await page.locator('.annotation-reply-picker .rich-editor-content').innerText(), 'Reply 中文\nSecond line')
    assert.ok(await page.locator('.annotation-dialog .rich-editor-content').first().locator('[style*="font-weight"]').count())
    const restoredEditor = page.locator('.annotation-dialog .rich-editor-content').first()
    await select(restoredEditor, 1, 3)
    await page.keyboard.press('Control+b')
    await page.locator('.annotation-dialog .modal-actions .primary').click()
    await page.locator('.quick-save').click()
    await page.waitForFunction(() => document.querySelector('.quick-save')?.disabled)
    const toggled = await PDFDocument.load(await fs.readFile(file))
    const toggledMarks = JSON.parse(toggled.context.lookup(toggled.getPage(0).node.Annots().get(0)).get(PDFName.of('PDFuckMarks')).decodeText())
    assert.ok(toggledMarks.some(mark => mark.start === 1 && mark.end === 3 && !mark.bold && mark.italic && mark.underline && mark.highlight), 'Removing a saved format must survive another save')
    console.log(JSON.stringify({ version, doubleClick: 'passed', longText: content.length, fixedHeader: bounds, formatting: ['bold', 'italic', 'underline', 'highlight'], replyFormatting: 'passed', pdfSaveReopen: 'passed' }))
  } finally { if (app) await close(); await fs.rm(temporary, { recursive: true, force: true }) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
